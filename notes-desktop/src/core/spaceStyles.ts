/** The reference `风格/<name>.md` for one look. */
export function spaceStyleReference(style: SpaceStyle): string {
  return [
    `# 风格参考：${style.name}`,
    "",
    style.summary,
    "",
    `- 预览图：同一文件夹的 ${style.name}.jpg`,
    `- 出处：[${style.source.title}](${style.source.url})（复刻，内容换成了中文健身空间）`,
    "",
    notes[style.id],
    adapting,
    "",
    "## 参考代码",
    "",
    "```html",
    code[style.id].trim(),
    "```",
    "",
  ].join("\n");
}

/** Every file of the references, by name inside `风格/`. */
export function spaceStyleFiles(): { name: string; content: string | Buffer }[] {
  return spaceStyles.flatMap((style) => [
    { name: `${style.name}.md`, content: spaceStyleReference(style) },
    { name: `${style.name}.jpg`, content: Buffer.from(style.preview, "base64") },
  ]);
}
